/* Ready service worker
   Network-first for the app's own files: online you always get the newest
   version, offline it loads the saved copy. Weather alerts and place search
   are never cached here; the app saves the last alerts itself and labels
   them with the time they were checked. */

const CACHE = "ready-v1"; // bump this (ready-v2, ...) if you ever need to wipe old caches

const CORE = [
  "./",
  "./index.html",
  "./style.css",
  "./app.js",
  "./manifest.json",
  "./icon-192.png",
  "./icon-512.png",
  "./apple-touch-icon.png",
];

// Live data: always go straight to the network.
const LIVE_HOSTS = ["api.weather.gov", "nominatim.openstreetmap.org"];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(CORE)));
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  if (LIVE_HOSTS.includes(new URL(req.url).hostname)) return; // let the browser handle it

  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res && (res.ok || res.type === "opaque")) {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(req, copy));
        }
        return res;
      })
      .catch(() =>
        caches.match(req).then((hit) => {
          if (hit) return hit;
          if (req.mode === "navigate") return caches.match("./index.html");
          return Response.error();
        })
      )
  );
});
